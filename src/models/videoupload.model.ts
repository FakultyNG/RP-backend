import { HydratedDocumentFromSchema, InferSchemaType, Schema, model } from 'mongoose'
import { S3 } from '../services/aws/s3'
import { videoUploadParents } from './assets'

const resolutionsSchema = new Schema(
  {
    resolution: {
      type: String,
      enum: ['1080', '720', '480'],
      required: true,
    },

    key: {
      type: String,
      required: true,
    },
  },
  { _id: false, timestamps: false, versionKey: false },
)

const schema = new Schema(
  {
    bucket: {
      type: String,
      required: true,
    },

    key: {
      type: String,
      required: true,
      unique: true,
    },

    mimetype: {
      type: String,
    },

    size: {
      type: Number,
    },

    isTranscoded: {
      type: Boolean,
      default: false,
    },

    parentType: {
      type: String,
      enum: videoUploadParents, // add more as needed
    },

    parentId: {
      type: Schema.Types.ObjectId,
      requires: true,
    },

    resolutions: [resolutionsSchema],

    /** HLS multivariant playlist generated by the Railway MediaConvert pipeline. */
    hlsKey: {
      type: String,
      default: null,
    },

    hlsStatus: {
      type: String,
      enum: ['pending', 'processing', 'ready', 'failed'],
      default: 'pending',
    },

    hlsJobId: {
      type: String,
      default: null,
    },

    hlsError: {
      type: String,
      default: null,
    },
  },
  {
    timestamps: true,
    versionKey: false,
  },
)

schema.index(
  { isTranscoded: 1 },
  {
    partialFilterExpression: { isTranscoded: false },
    name: '_isTranscodedStatus',
  },
)

schema.index({ hlsStatus: 1 }, { name: '_railwayHlsStatus' })

export const VideoUploadModel = model('video_uploads', schema)
export type VideoUpload = HydratedDocumentFromSchema<typeof schema>
export type VideoUploadSchema = InferSchemaType<typeof schema>
